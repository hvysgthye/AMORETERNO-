import assert from 'node:assert/strict';
import { encodeDedicationToURL, decodeDedicationFromURL } from '../src/utils/shareHelper.js';
import { generateStandaloneHTML } from '../src/utils/htmlExporter.js';
globalThis.window = { location: { origin: 'https://example.com', pathname: '/gift/', search: '' } };
const data = { title: 'Para ti 💌', letterText: 'Con cariño, siempre.', badgeText: '', hidePhoto: true, customSign: 'Ana', combo1: 7, photos: ['https://example.com/photo.jpg','data:image/png;base64,AAAA'], customAudio: 'data:audio/mp3;base64,AAAA' };
const url = encodeDedicationToURL('carta', data);
window.location.search = new URL(url).search;
const restored = decodeDedicationFromURL();
assert.equal(restored.isRecipientMode, true);
assert.equal(restored.templateId, 'carta');
for (const key of ['title','letterText','badgeText','hidePhoto','customSign','combo1']) assert.equal(restored.data[key], data[key]);
assert.deepEqual(restored.data.photos, ['https://example.com/photo.jpg']);
assert.equal(restored.data.customAudio, null);
window.location.search = '?mode=view&d=invalid';
assert.equal(decodeDedicationFromURL().isRecipientMode, false);
const html = generateStandaloneHTML('carta', data);
assert.ok(html.includes('Con cariño, siempre.'));
assert.ok(html.includes('data:audio/mp3;base64,AAAA'));
console.log('PASS: Unicode, hidden/empty fields, signature, combination, media policy, malformed URL and export.');
