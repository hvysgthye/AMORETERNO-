import { createServer } from 'vite';
import { renderToStaticMarkup } from 'react-dom/server';
import React from 'react';
import { writeFile } from 'node:fs/promises';
import { KEEPSAKE_DESIGNS } from '../src/data/keepsakeDesigns.js';

// Produce the same original illustrations for the plain-HTML export. The
// downloaded gift needs neither React nor a server to display these drawings.
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { default: Artwork } = await server.ssrLoadModule('/src/components/templates/shared/KeepsakeArtwork.jsx');
  const artwork = Object.fromEntries(Object.keys(KEEPSAKE_DESIGNS).map(templateId => [
    templateId, renderToStaticMarkup(React.createElement(Artwork, { templateId }))
  ]));
  await writeFile(new URL('../src/data/keepsakeArtwork.js', import.meta.url),
    '// Generated by npm run artwork from the original SVG components.\nexport const KEEPSAKE_ARTWORK = ' + JSON.stringify(artwork, null, 2) + ';\n');
  console.log(`Generated ${Object.keys(artwork).length} original gift illustrations.`);
} finally {
  await server.close();
}
